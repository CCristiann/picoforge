"""Freeze qwen35 L/N/M ranges from tokenizers' actual Regex backend.

No assumption that Python regex, Unicode tables and Oniguruma share a version.
Run with the existing venv. Retains the handwritten runtime below the marker.
"""
import importlib.metadata
from pathlib import Path
from tokenizers import Regex
from tokenizers.pre_tokenizers import Split
from tokenizers.normalizers import NFD, NFC
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
assert importlib.metadata.version("tokenizers") == "0.22.2"
path = ROOT / "src/qwen38_unicode.c"
marker = "/* END GENERATED CATEGORIES */"
tail = path.read_text().split(marker, 1)[1] if path.exists() else "\n"
lines = ['/* Generated by tools/gen_qwen38_unicode.py; tokenizers 0.22.2.',
         ' * Categories and NFC are probed from their actual backend, separately. */',
         '#include "qwen38_a_internal.h"', '']
for prop in "LNM":
    ranges = []
    split = Split(Regex(r"[^\p{"+prop+"}]"), behavior="removed")
    for lo, hi in [(0, 0xD800), (0xE000, 0x110000)]:
        text = "".join(chr(cp) for cp in range(lo, hi))
        ranges += [(lo+a, lo+b-1) for _, (a, b) in split.pre_tokenize_str(text)]
    lines.append(f"static const CodepointRange category_{prop}[] = {{")
    lines += ["    "+", ".join(f"{{0x{a:X},0x{b:X}}}" for a, b in ranges[i:i+4])+","
              for i in range(0, len(ranges), 4)]
    lines.append("};")
    print(prop, len(ranges), "ranges")
nfd, nfc = NFD().normalize_str, NFC().normalize_str
# Python supplies stable representative CCC labels ONLY. Membership, ordering,
# decompositions and composition exclusions all come from the pinned backend.
reps = {}
for cp in range(0x110000):
    if 0xD800 <= cp < 0xE000: continue
    char = chr(cp)
    cc = unicodedata.combining(char)
    if cc and cc not in reps and nfd(char) == char: reps[cc] = char
classes = sorted(reps)
decomps, payload, combining, compositions = [], [], [], []
for cp in range(0x110000):
    if 0xD800 <= cp < 0xE000 or 0xAC00 <= cp < 0xAC00+11172: continue
    char = chr(cp)
    dec = nfd(char)
    if dec != char:
        decomps.append((cp, len(payload), len(dec)))
        payload += list(map(ord, dec))
        if len(dec) >= 2 and nfc(dec) == char and len(nfc(dec[:-1])) == 1:
            compositions.append((ord(nfc(dec[:-1])), ord(dec[-1]), cp))
        continue
    # Primitive marks are exactly those that reorder against CCC 1 or 240.
    if (nfd('a'+char+reps[1]) != 'a'+reps[1]+char and
            nfd('a'+reps[240]+char) != 'a'+char+reps[240]): continue
    lo, hi = 0, len(classes)
    while lo < hi:
        mid = (lo+hi)//2
        if nfd('a'+char+reps[classes[mid]]) == 'a'+reps[classes[mid]]+char and char != reps[classes[mid]]:
            lo = mid+1
        else: hi = mid
    assert lo < len(classes)
    cc = classes[lo]
    # Equality of canonical class preserves BOTH input orders.
    assert nfd('a'+char+reps[cc]) == 'a'+char+reps[cc]
    assert nfd('a'+reps[cc]+char) == 'a'+reps[cc]+char
    combining.append((cp, cc))
lines += ['typedef struct { unsigned cp, offset, len; } Q38Nfd;',
          'static const Q38Nfd nfd_table[] = {']
lines += [f'    {{0x{cp:X},{offset},{n}}},' for cp, offset, n in decomps]
lines += ['};', 'static const unsigned nfd_payload[] = {']
lines += ['    '+','.join(hex(x) for x in payload[i:i+12])+',' for i in range(0,len(payload),12)]
lines += ['};', 'static const CombiningClass nfc_ccc[] = {']
lines += [f'    {{0x{cp:X},{cc}}},' for cp, cc in combining]
lines += ['};', 'static const Composition nfc_compose[] = {']
lines += [f'    {{0x{a:X},0x{b:X},0x{cp:X}}},' for a, b, cp in sorted(compositions)]
lines += ['};']
print('NFC:', len(decomps), 'NFD entries;', len(combining), 'CCC;', len(compositions), 'pairs')
path.write_text("\n".join(lines)+"\n"+marker+tail)
